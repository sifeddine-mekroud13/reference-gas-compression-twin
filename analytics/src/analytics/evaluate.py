"""Run the M8 evaluation and write docs/analytics-results.md.

Usage: uv run python -m analytics.evaluate [--hours 1.0]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from . import vibration
from .anomaly import PCAMonitor, SimilarityModel, metrics, persistence
from .data import FEATURES, dataset
from .soft_sensor import SoftSensor

ROOT = Path(__file__).resolve().parents[3]


def run(hours: float) -> dict[str, object]:
    runs = dataset(hours=hours)
    normal = next(r for r in runs if r.name == "normal")
    half = len(normal.x) // 2
    train, val = normal.x[:half], normal.x[half:]
    pca = PCAMonitor.fit(train)
    sim = SimilarityModel.fit(train)
    soft = SoftSensor.fit(train)
    tz = 3.0 * soft.resid_sd
    res: dict[str, object] = {"pca_components": int(pca.p.shape[1]), "train_samples": int(half)}
    rows = []
    t_val = normal.t[half:]
    for det_name, raw in (
        ("PCA T2/SPE", pca.flags(val)),
        ("Similarity (MSET-style)", sim.flags(val)),
        ("Soft sensor TT-2005", np.abs(soft.residual(val)) > tz),
    ):
        rows.append(
            {"detector": det_name, "case": "normal (held out)", **metrics(persistence(raw), np.zeros(len(val), int), t_val)}
        )
    for r in runs:
        if r.name == "normal":
            continue
        for det_name, raw in (
            ("PCA T2/SPE", pca.flags(r.x)),
            ("Similarity (MSET-style)", sim.flags(r.x)),
            ("Soft sensor TT-2005", np.abs(soft.residual(r.x)) > tz),
        ):
            rows.append({"detector": det_name, "case": r.name, **metrics(persistence(raw), r.label, r.t)})
        post = r.label == 1
        if post.any():
            c = pca.contributions(r.x[post]).mean(0) / np.maximum(pca.contributions(train).mean(0), 1e-9)
            rows[-3]["top_contributor"] = FEATURES[int(np.argmax(c))]
    res["anomaly"] = rows
    res["vibration"] = vibration.evaluate()
    return res


def fmt(v: object) -> str:
    if isinstance(v, float):
        if v != v:
            return "n/a"
        return "never" if v == float("inf") else f"{v:.3f}" if v < 10 else f"{v:.0f}"
    return str(v)


def write_md(res: dict[str, object]) -> str:
    lines = [
        "# Analytics results (M8)",
        "",
        "Generated by `uv run python -m analytics.evaluate`. Do not edit by hand.",
        "",
        "Data: plant simulator, measured (noisy, quantised) values at 10 s, 18 variables, ambient",
        "swing 3 degC. Training: first half of a 2 h healthy run; held-out second half gives the",
        "false alarm rate. Fault runs: 1 h, fault injected at t = 1200 s. Degradation rates are",
        "time compressed (fouling 4 %/h head) so these delays are NOT field delays.",
        "Alarm: 3 of 5 consecutive samples above the 99 % limit.",
        "",
        f"PCA retained {res['pca_components']} components (90 % variance).",
        "",
        "Top contributor: variable with the largest SPE contribution after onset, relative to its",
        "training mean contribution (raw contributions favour tightly controlled variables).",
        "",
        "| Detector | Case | False alarm rate | Detection delay (s) | Detection rate | Top SPE contributor |",
        "|---|---|---|---|---|---|",
    ]
    for r in res["anomaly"]:  # type: ignore[attr-defined]
        lines.append(
            f"| {r['detector']} | {r['case']} | {fmt(r['false_alarm_rate'])} | {fmt(r['detection_delay_s'])} "
            f"| {fmt(r['detection_rate'])} | {r.get('top_contributor', '')} |"
        )
    v = res["vibration"]
    lines += [
        "",
        "## Vibration fault classification (synthetic proximity probe waveforms)",
        "",
        "| Method | Accuracy | Macro F1 |",
        "|---|---|---|",
        f"| Random forest on order features | {v['rf_accuracy']:.3f} | {v['rf_macro_f1']:.3f} |",  # type: ignore[index]
        f"| Rule chart baseline | {v['rule_accuracy']:.3f} | {v['rule_macro_f1']:.3f} |",  # type: ignore[index]
        "",
        "## Reading these numbers honestly",
        "",
        "- Synthetic data with known physics favours every method: the generator and the",
        "  detector share assumptions. Expect much worse on real plant data.",
        "- The vibration classes are separable by construction; the interesting result is how",
        "  close a two-line analyst rule gets, which argues for rules plus ML, not ML alone.",
        "- PCA keeps 15 of 18 components: at a steady operating point most variance is sensor noise,",
        "  not process correlation. Training over several operating points would give a leaner model.",
        "- A stuck transmitter has near zero variance change; PCA catches it only once the process",
        "  moves. Dedicated validity checks (flatline, rate of change) belong in the collector.",
        "- Fan failure is mostly masked: fan staging and the remaining fans hold the cooler outlet",
        "  temperature, so the process barely moves. That is control doing its job, and why",
        "  equipment state (fan run feedback) must be monitored directly, not inferred.",
        "- Benchmarks on public data (TEP, CWRU, Paderborn, UCI naval) are scripted in",
        "  `analytics/benchmarks` but results are not reported here until run.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--hours", type=float, default=1.0)
    a = ap.parse_args()
    res = run(a.hours)
    (ROOT / "docs" / "analytics-results.md").write_text(write_md(res))
    print(json.dumps(res, indent=1, default=str))


if __name__ == "__main__":
    main()
